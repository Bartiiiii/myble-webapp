function czechDil(n: number): string {
  if (n === 1) return "díl";
  if (n >= 2 && n <= 4) return "díly";
  return "dílů";
}

function czechNavrh(n: number): string {
  if (n === 1) return "návrh";
  if (n >= 2 && n <= 4) return "návrhy";
  return "návrhů";
}

